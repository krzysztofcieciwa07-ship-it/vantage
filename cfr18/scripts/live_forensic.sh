#!/bin/sh
set -eu
ROOT="$(CDPATH= cd -- "$(dirname "$0")/.." && pwd)"; cd "$ROOT"

USER_SEED=$(printenv USER_SEED 2>/dev/null || true)
if [ -z "$USER_SEED" ]; then USER_SEED=12345; fi
export USER_SEED

CFR_PARTICIPANT_SUBMISSION=$(printenv CFR_PARTICIPANT_SUBMISSION 2>/dev/null || true)
if [ -z "$CFR_PARTICIPANT_SUBMISSION" ] || [ ! -s "$CFR_PARTICIPANT_SUBMISSION" ]; then
  echo "BLOCK: set CFR_PARTICIPANT_SUBMISSION to a separate, non-empty participant JSON file" >&2
  exit 2
fi

# Preserve the supplied input before cleaning generated evidence. The source file
# may itself live beneath evidence/; it is never edited or generated by this harness.
SUBMISSION_TMP=$(mktemp)
trap 'rm -f "$SUBMISSION_TMP"' EXIT
cp "$CFR_PARTICIPANT_SUBMISSION" "$SUBMISSION_TMP"

rm -rf data/* evidence/*.json evidence/*.jsonl evidence/.chain.jsonl
mkdir -p data evidence
cp "$SUBMISSION_TMP" evidence/participant_submission.json
rm -f "$SUBMISSION_TMP"
python3 -m ci.evidence_vault session-start
python3 -m ci.gen_incident --seed "$USER_SEED" >/tmp/cfr18-incident.json
python3 - <<'PY'
from pathlib import Path
from . import __package__
from ci.evidence_vault import append, file_sha256

submission = Path("evidence/participant_submission.json")
append(
    "participant_submission_received",
    {"path": str(submission), "sha256": file_sha256(submission)},
)
PY

docker compose down -v --remove-orphans >/dev/null 2>&1 || true
docker compose up -d --build
trap 'docker compose down -v --remove-orphans >/dev/null 2>&1 || true; rm -f "$SUBMISSION_TMP"' EXIT
until curl -fsS http://localhost:8098/health >/dev/null; do sleep 1; done
for i in $(seq 1 8); do
  curl -fsS -X POST http://localhost:8098/enqueue -H 'content-type: application/json' -d "{\"id\":$i}" >/dev/null
done
sleep 1
docker compose stop worker
DEDUP=1 CRASH_ONCE=0 docker compose up -d worker
for i in $(seq 1 30); do
  [ -f data/processed.jsonl ] && [ "$(wc -l < data/processed.jsonl)" -ge 8 ] && break
  sleep 1
done
python3 - <<'PY'
import json
from pathlib import Path

rows = [json.loads(line) for line in Path("data/processed.jsonl").read_text().splitlines() if line.strip()]
ids = [row["id"] for row in rows]
assert set(ids) == set(range(1, 9)) and len(ids) == len(set(ids))
events = [json.loads(line) for line in Path("data/events.jsonl").read_text().splitlines() if line.strip()]
assert any(event.get("event") == "crash" for event in events)
PY

DURATION=$(python3 - <<'PY'
import json
from pathlib import Path

incident = json.loads(Path("evidence/incident.json").read_text())
print(int(incident["hidden_required_window_s"]))
PY
)
DURATION="$DURATION" sh scripts/probe.sh
python3 -m ci.evidence_vault snapshot \
  evidence/incident.json \
  evidence/manifest.json \
  evidence/probe_results.jsonl \
  evidence/participant_submission.json \
  data/events.jsonl \
  data/processed.jsonl
cp evidence/probe_results.jsonl /tmp/cfr18-probe.bak
printf '\n{"tampered":true}' >> evidence/probe_results.jsonl
if python3 -m ci.evidence_vault verify-bound >/dev/null 2>&1; then
  echo "EVIDENCE_FILE_TAMPER_GATE: FAIL"
  exit 1
fi
mv /tmp/cfr18-probe.bak evidence/probe_results.jsonl
python3 -m ci.evidence_vault verify-bound
python3 -m ci.score
python3 -m ci.evidence_vault verify
echo LIVE_FORENSIC_PASS
